// Writes packages/abi/src/index.ts and packages/abi/abis/<Name>.json from the forge artifacts in
// contracts/out. Build them first: cd contracts && $FOUNDRY_BIN/forge build.
//
//   bun packages/abi/scripts/generate.ts           write
//   bun packages/abi/scripts/generate.ts --check   exit 1 if the files differ from what would be written
import { join } from "node:path";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const ROOT = join(import.meta.dirname, "../../..");
const SRC = join(import.meta.dirname, "../src");
const ABIS = join(import.meta.dirname, "../abis");

// Core is the protocol. The rest is test code of the local chain (31337): the two test tokens, the
// account factory of a giver not deployed yet, and the forwarder that stands in for Multicall3.
export const TARGETS = {
  AHandCore: "contracts/out/AHandCore.sol/AHandCore.json",
  MockUSD: "contracts/out/MockUSD.sol/MockUSD.json",
  BlacklistToken: "contracts/out/BlacklistToken.sol/BlacklistToken.json",
  KeyAccountFactory: "contracts/out/KeyAccount.sol/KeyAccountFactory.json",
  KeyAccount: "contracts/out/KeyAccount.sol/KeyAccount.json",
  Forwarder: "contracts/out/Forwarder.sol/Forwarder.json",
} as const;

export function render(): Map<string, string> {
  const files = new Map<string, string>();
  let index = `// Generated by packages/abi/scripts/generate.ts from contracts/out. Do not edit by hand.\n`;
  for (const [name, relPath] of Object.entries(TARGETS)) {
    const path = join(ROOT, relPath);
    if (!existsSync(path)) throw new Error(`No forge artifact for ${name} at ${relPath}: run forge build in contracts/`);
    const abi = JSON.parse(readFileSync(path, "utf-8")).abi;
    if (!Array.isArray(abi)) throw new Error(`No ABI in ${relPath}`);
    index += `\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
    files.set(join(ABIS, `${name}.json`), JSON.stringify(abi, null, 2) + "\n");
  }
  index += `\nexport type { Deployment, DeploymentToken, TokenKind, HexAddress, Hex32 } from "./deployment.js";\n`;
  index += `export { parseDeployment, DeploymentError } from "./deployment.js";\n`;
  files.set(join(SRC, "index.ts"), index);
  return files;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const stale: string[] = [];
  mkdirSync(ABIS, { recursive: true });
  for (const [path, content] of render()) {
    const current = existsSync(path) ? readFileSync(path, "utf-8") : null;
    if (current === content) continue;
    if (check) stale.push(path);
    else writeFileSync(path, content);
  }
  if (check && stale.length > 0) {
    console.error(`stale, run bun packages/abi/scripts/generate.ts:\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log(check ? "packages/abi is up to date with contracts/out" : "packages/abi written from contracts/out");
}
