const WORDS: Record<Lang, Record<string, string>> = { en, ru };
const COMMON: Record<Lang, Record<string, string>> = { en: commonEn, ru: commonRu };

/** The page's sentence for `key` in `lang`, with {name} filled in. Core's and the links' come from i18n/common. */
export function say(lang: Lang, key: WordKey | `core.${string}` | `link.${string}`, values: Record<string, string | number> = {}): string {
  const text = WORDS[lang][key] ?? COMMON[lang][key] ?? COMMON.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}

/** The language to start in: the browser's, if Russian; English otherwise. */
export function startLang(languages: readonly string[]): Lang {
  return languages.some((tag) => tag.toLowerCase().startsWith("ru")) ? "ru" : "en";
}
