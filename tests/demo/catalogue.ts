/**
 * Writes tests/demo/CATALOGUE.md, the living catalogue of use cases, from the scenarios
 * themselves: what each scenario shows (its story and its steps as sentences), which use cases
 * it covers, and the coverage of every tracked use case. Run it after changing a scenario;
 * `--check` fails when the file on disk differs (for CI), so the catalogue never drifts.
 *
 *   bun tests/demo/catalogue.ts [--check]
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

import type { Expectation } from "./engine/scenario";
import { captionOf } from "./engine/verbs";
import { SCENARIOS } from "./scenarios";
import { PLANNED, USE_CASES } from "./scenarios/use-cases";
import { handModel } from "./model/hand";
import { coverage, modelPaths, wordsOf } from "./model/paths";
import { scenarioOf } from "./model/generate";

const FILE = join(import.meta.dirname, "CATALOGUE.md");

function render(): string {
  const lines: string[] = [];
  lines.push("# aHand use cases: the catalogue", "", "Generated by `bun tests/demo/catalogue.ts` from `tests/demo/scenarios/`. Do not edit by hand.", "");
  lines.push("Play one: `DEMO=1 DEMO_ONLY=<id> STAND_SLOT=<n> bunx playwright test -c playwright.demo.config.ts`.", "");
  lines.push("## Coverage", "", "| Use case | | Covered by | Planned |", "|---|---|---|---|");
  for (const uc of USE_CASES) {
    const by = SCENARIOS.filter((s) => s.covers.includes(uc.id)).map((s) => `[${s.id}](#${s.id})`);
    const planned = PLANNED.filter((p) => p.covers.includes(uc.id)).map((p) => p.id);
    const mark = by.length ? "✅" : uc.reach === "browser" ? (planned.length ? "📝" : "⬜") : uc.reach === "core" ? "⚙️ Core/SDK" : "— not built";
    lines.push(`| ${uc.id} ${uc.name} | ${mark} | ${by.join(", ")} | ${planned.join(", ")} |`);
  }
  lines.push("", "✅ a scenario shows it · 📝 planned · ⬜ no scenario yet · ⚙️ tested below the browser only · — no screen for it", "");
  lines.push(...model(), "## Scenarios", "");
  for (const s of SCENARIOS) {
    lines.push(`### ${s.id}`, "", `**${s.title}**`, "", s.story, "");
    lines.push(`Runs on: ${s.targets.join(", ")} · covers: ${s.covers.join(", ")}${s.tags?.length ? ` · tags: ${s.tags.join(", ")}` : ""}`, "");
    lines.push("| Persona | Role | Wallet |", "|---|---|---|");
    for (const p of Object.values(s.personas)) lines.push(`| ${p.name} | ${p.role} | ${p.wallet.kind === "dev" ? `dev account ${p.wallet.account}` : p.wallet.kind === "injected" ? `injected key ${p.wallet.account}` : p.wallet.kind === "privy-test" ? `Privy test account ${p.wallet.account}` : p.wallet.kind === "burner" ? `burner ${p.wallet.index}` : "none"} |`);
    lines.push("");
    s.steps.forEach((step, i) => {
      lines.push(`${i + 1}. ${step.caption ?? captionOf(step, step.who ? s.personas[step.who]!.name : undefined)}`);
      for (const e of step.form ?? []) lines.push(`   - before the swipe: ${describe(e)}`);
      for (const e of step.expect ?? []) lines.push(`   - ${describe(e)}`);
    });
    lines.push("", "Checked on the chain at the end:", "");
    for (const c of s.checks) {
      if ("state" in c) lines.push(`- Hand "${c.hand}" is ${c.state}`);
      else if ("received" in c) lines.push(`- ${name(s.personas, c.received)} received ${c.amount} ${c.token === "blacklist" ? "test dollars that can block" : "test dollars"}`);
      else lines.push(`- the asker of "${c.askerWhole}" has the whole reward back`);
    }
    if (s.watch?.length) lines.push("", `Every persona's browser: ${s.watch.join(", ")}.`);
    lines.push("");
  }
  lines.push("## Planned", "");
  for (const p of PLANNED) lines.push(`- **${p.id}**: ${p.title} (${p.covers.join(", ")})${p.waitsFor ? `. Waits for ${p.waitsFor}.` : ""}`);
  lines.push("");
  return lines.join("\n");
}

/** The Hand model (tests/demo/model): its graph, and which of its ends the scenarios above reach. */
function model(): string[] {
  const lines = ["## The Hand model", ""];
  lines.push("`tests/demo/model/hand.ts` is one Hand's life with Core's rules as guards, kept small (at most two passes, one answer, one top-up, one extension). Every scenario's Hands are read back as paths through it (`model/paths.ts`); a step the model forbids fails this file's generation.", "");
  lines.push("```mermaid", "stateDiagram-v2", "  [*] --> idea");
  const states = handModel.config.states as Record<string, { on?: Record<string, string | { target?: string; guard?: string }>; type?: string }>;
  for (const [from, node] of Object.entries(states)) {
    for (const [event, to] of Object.entries(node.on ?? {})) {
      const target = typeof to === "string" ? to : (to.target ?? from);
      const guard = typeof to === "string" || !to.guard ? "" : ` [${to.guard}]`;
      lines.push(`  ${from} --> ${target}: ${event}${guard}`);
    }
    if (node.type === "final") lines.push(`  ${from} --> [*]`);
  }
  lines.push("```", "");
  const cov = coverage(SCENARIOS, modelPaths("shortest"));
  const reached = cov.paths.filter((p) => p.sameEnd.length).length;
  lines.push(`Ends of a Hand (state, passes, answers, top-ups, extensions): **${reached} of ${cov.paths.length}** reached by a scenario above; transitions taken: ${cov.allTransitions - cov.untakenTransitions.length} of ${cov.allTransitions}. Every end has a generated scenario (\`DEMO_MODEL=gaps\` plays the ones marked ⬜).`, "");
  lines.push("| End | | Reached by | Shortest path (generated scenario) |", "|---|---|---|---|");
  for (const p of cov.paths) lines.push(`| ${p.path.key} | ${p.sameEnd.length ? "✅" : "⬜"} | ${p.sameEnd.map((id) => `[${id}](#${id.split(" ")[0]})`).join(", ")} | ${wordsOf(p.path.events)} (\`${scenarioOf(p.path).id}\`) |`);
  lines.push("");
  return lines;
}

export function name(personas: Record<string, { name: string }>, ref: string): string {
  const key = ref.replace(/^@/, "");
  return personas[key]?.name ?? `the address “${key}”`;
}

/** One line per expectation, in plain words. */
export function describe(e: Expectation): string {
  if ("see" in e) {
    const parts = [e.count !== undefined ? `${e.count} × \`${e.see}\`` : `\`${e.see}\` shows`];
    if (e.says) parts.push(`says ${typeof e.says === "string" ? e.says : `${e.says[0]} (${Object.entries(e.says[1]).map(([k, v]) => `${k}=${v}`).join(", ")})`}`);
    if (e.notSays) parts.push(`not ${e.notSays}`);
    if (e.text) parts.push(`“${e.text}”`);
    for (const [k, v] of Object.entries(e.attr ?? {})) parts.push(`${k}=${v}`);
    if (e.enabled !== undefined) parts.push(e.enabled ? "enabled" : "disabled");
    return `screen${e.on ? ` of ${e.on}` : ""}: ${parts.join(", ")}`;
  }
  if ("sdk" in e) return `the SDK reads ${e.sdk} as ${e.state}`;
  if ("open" in e) return `opens “${e.open}”`;
  if ("hand" in e) return `Core: Hand "${e.hand}" ${Object.entries(e).filter(([k]) => k !== "hand").map(([k, v]) => `${k} ${v}`).join(", ")}`;
  if ("route" in e) return `Core's checkRoute on ${e.route}: ${e.is.length ? e.is.map((r) => `${r.payee ?? "nobody"} keeps ${r.keptBps / 100}%`).join(", then ") : "no passes"}`;
  if ("give" in e) return `Core's checkGive on ${e.give}: ${e.core}${e.payee ? `, pays ${e.payee}` : ""}${e.claimBps !== undefined ? `, claims ${e.claimBps / 100}%` : ""}`;
  if ("balance" in e) return `balance of ${e.balance}${e.token === "blacklist" ? " (token that can block)" : ""}: ${e.is !== undefined ? `is ${e.is}` : `changes by ${e.change}`}`;
  if ("pending" in e) return `Core holds ${e.is} for ${e.pending}`;
  if ("tx" in e) return `the transaction: ${[e.tx.events ? `events ${e.tx.events.join(" → ")}` : "", e.tx.payouts ? (e.tx.payouts.length ? `payouts ${e.tx.payouts.map((p) => `${p.amount} ${p.kind} to ${p.payee}`).join(", ")}` : "no payouts") : ""].filter(Boolean).join("; ")}`;
  if ("origins" in e) return `the browser reached only: ${e.origins.join(", ")}`;
  if ("withdrawn" in e) return `Core emitted Withdrawn for ${e.withdrawn} ${e.count} time(s)`;
  if ("link" in e) return `the address of ${e.link} has the ${e.shape} shape`;
  return `${e.assert}${e.arg ? ` (${e.arg.length > 40 ? `${e.arg.slice(0, 40)}…` : e.arg})` : ""}`;
}

if (import.meta.main) main();

function main(): void {
  const text = render();
  if (process.argv.includes("--check")) {
    const now = existsSync(FILE) ? readFileSync(FILE, "utf8") : "";
    if (now !== text) {
      console.error("tests/demo/CATALOGUE.md is out of date: run bun tests/demo/catalogue.ts");
      process.exit(1);
    }
    console.log("CATALOGUE.md is up to date");
  } else {
    writeFileSync(FILE, text);
    console.log(`wrote ${FILE}: ${SCENARIOS.length} scenarios, ${PLANNED.length} planned`);
  }
}
